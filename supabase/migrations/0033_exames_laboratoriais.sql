-- Módulo de Exames Laboratoriais: duas frentes independentes.
--
-- 1) Solicitações — documento de texto livre (pedido de exames), mesmo
--    padrão de listas_recomendacoes/orientacoes_nutricionais (migrations
--    0009/0011), com modelos reutilizáveis. Diferença: cada solicitação
--    tem um token_publico próprio (não reaproveita o token do paciente)
--    porque o PDF carrega um QR Code que aponta pra ELA especificamente
--    — é um documento médico, precisa validar sozinho.
--
-- 2) Registros — resultados de exames organizados em grupos (Hemograma,
--    Perfil Lipídico etc), cada exame com valor obtido, unidade e
--    intervalo de referência próprios (preenchidos olhando o laudo em
--    mãos — o catálogo do app só sugere um prefill genérico, referências
--    variam bastante entre laboratórios). valor_obtido é texto, não
--    numérico, porque vários exames têm resultado qualitativo
--    ("Não Reagente", "Indetectável", "Negativo").

-- ============================================================
-- SOLICITAÇÕES
-- ============================================================
create table if not exists public.exames_solicitacoes (
  id            bigint generated by default as identity primary key,
  id_paciente   bigint not null references public.pacientes(id) on delete cascade,
  id_avaliador  uuid not null references auth.users(id) on delete cascade,
  titulo        text not null default '1ª Solicitação de exames',
  conteudo      text,
  token_publico uuid not null default gen_random_uuid() unique,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists idx_exames_solicitacoes_paciente on public.exames_solicitacoes(id_paciente);
create index if not exists idx_exames_solicitacoes_avaliador on public.exames_solicitacoes(id_avaliador);

alter table public.exames_solicitacoes enable row level security;

drop policy if exists "exames_solicitacoes_isolamento_avaliador" on public.exames_solicitacoes;
create policy "exames_solicitacoes_isolamento_avaliador" on public.exames_solicitacoes
  for all using (id_avaliador = auth.uid())
  with check (id_avaliador = auth.uid());

-- Leitura pública via token — mesmo padrão (e mesmo nível de confiança)
-- já usado pra avaliações/planos/orientações em
-- 0018_area_paciente_leitura_publica.sql: a tabela toda fica legível pro
-- anônimo, mas o app só busca por token_publico específico (aleatório,
-- não listável).
drop policy if exists "exames_solicitacoes_leitura_publica_via_token" on public.exames_solicitacoes;
create policy "exames_solicitacoes_leitura_publica_via_token" on public.exames_solicitacoes
  for select to anon using (true);


create table if not exists public.modelos_exames_solicitacoes (
  id            bigint generated by default as identity primary key,
  id_avaliador  uuid references auth.users(id) on delete cascade,
  titulo        text not null default 'Modelo',
  conteudo      text,
  created_at    timestamptz not null default now()
);

-- id_avaliador nullable de propósito: linhas com id_avaliador is null são
-- modelos do SISTEMA (os dois perfis prontos abaixo), visíveis pra todo
-- nutricionista — não só quem os criou.
create index if not exists idx_modelos_exames_solicitacoes_avaliador on public.modelos_exames_solicitacoes(id_avaliador);

alter table public.modelos_exames_solicitacoes enable row level security;

drop policy if exists "modelos_exames_solicitacoes_leitura" on public.modelos_exames_solicitacoes;
create policy "modelos_exames_solicitacoes_leitura" on public.modelos_exames_solicitacoes
  for select using (id_avaliador is null or id_avaliador = auth.uid());

drop policy if exists "modelos_exames_solicitacoes_escrita" on public.modelos_exames_solicitacoes;
create policy "modelos_exames_solicitacoes_escrita" on public.modelos_exames_solicitacoes
  for insert with check (id_avaliador = auth.uid());

drop policy if exists "modelos_exames_solicitacoes_update" on public.modelos_exames_solicitacoes;
create policy "modelos_exames_solicitacoes_update" on public.modelos_exames_solicitacoes
  for update using (id_avaliador = auth.uid()) with check (id_avaliador = auth.uid());

drop policy if exists "modelos_exames_solicitacoes_delete" on public.modelos_exames_solicitacoes;
create policy "modelos_exames_solicitacoes_delete" on public.modelos_exames_solicitacoes
  for delete using (id_avaliador = auth.uid());

