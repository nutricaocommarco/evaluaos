-- ============================================================
-- REGISTROS (resultados)
-- ============================================================
create table if not exists public.exames_registros (
  id            bigint generated by default as identity primary key,
  id_paciente   bigint not null references public.pacientes(id) on delete cascade,
  id_avaliador  uuid not null references auth.users(id) on delete cascade,
  titulo        text not null default '1º Registro de exames',
  data_coleta   date not null default current_date,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists idx_exames_registros_paciente on public.exames_registros(id_paciente);
create index if not exists idx_exames_registros_avaliador on public.exames_registros(id_avaliador);

alter table public.exames_registros enable row level security;

drop policy if exists "exames_registros_isolamento_avaliador" on public.exames_registros;
create policy "exames_registros_isolamento_avaliador" on public.exames_registros
  for all using (id_avaliador = auth.uid())
  with check (id_avaliador = auth.uid());


create table if not exists public.exames_registros_grupos (
  id           bigint generated by default as identity primary key,
  id_registro  bigint not null references public.exames_registros(id) on delete cascade,
  nome         text not null default 'Grupo',
  ordem        integer not null default 0
);

create index if not exists idx_exames_registros_grupos_registro on public.exames_registros_grupos(id_registro);

alter table public.exames_registros_grupos enable row level security;

drop policy if exists "exames_registros_grupos_via_registro" on public.exames_registros_grupos;
create policy "exames_registros_grupos_via_registro" on public.exames_registros_grupos
  for all using (
    exists (select 1 from public.exames_registros r where r.id = exames_registros_grupos.id_registro and r.id_avaliador = auth.uid())
  )
  with check (
    exists (select 1 from public.exames_registros r where r.id = exames_registros_grupos.id_registro and r.id_avaliador = auth.uid())
  );


create table if not exists public.exames_registros_itens (
  id             bigint generated by default as identity primary key,
  id_grupo       bigint references public.exames_registros_grupos(id) on delete cascade,
  id_registro    bigint not null references public.exames_registros(id) on delete cascade,
  nome_exame     text not null,
  valor_obtido   text,
  unidade        text,
  intervalo_min  numeric,
  intervalo_max  numeric,
  ordem          integer not null default 0
);

-- id_registro duplicado aqui (além de id_grupo) pra permitir "exame
-- avulso" sem grupo (id_grupo null) e ainda assim escopar a RLS
-- diretamente pelo registro, sem depender de um grupo existir.
create index if not exists idx_exames_registros_itens_grupo on public.exames_registros_itens(id_grupo);
create index if not exists idx_exames_registros_itens_registro on public.exames_registros_itens(id_registro);

alter table public.exames_registros_itens enable row level security;

drop policy if exists "exames_registros_itens_via_registro" on public.exames_registros_itens;
create policy "exames_registros_itens_via_registro" on public.exames_registros_itens
  for all using (
    exists (select 1 from public.exames_registros r where r.id = exames_registros_itens.id_registro and r.id_avaliador = auth.uid())
  )
  with check (
    exists (select 1 from public.exames_registros r where r.id = exames_registros_itens.id_registro and r.id_avaliador = auth.uid())
  );
